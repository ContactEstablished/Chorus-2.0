// D92: the app commands `src/ipc.rs` registers, read from its `collect_commands!` list. Shared by
// `build.rs` (the app manifest and the main window's permission set) and `ipc::tests` (which checks
// the list against the generated bindings).

/// Each registered command's name, in registration order: the last path segment of every entry.
pub fn registered_commands(ipc_source: &str) -> Vec<String> {
    let Some(start) = ipc_source.find("collect_commands![") else { return Vec::new() };
    let body = &ipc_source[start + "collect_commands![".len()..];
    let body = &body[..body.find(']').unwrap_or(0)];
    body.lines()
        .map(|line| line.split("//").next().unwrap_or_default())
        .flat_map(|line| line.split(','))
        .map(str::trim)
        .filter(|entry| !entry.is_empty())
        .map(|entry| entry.rsplit("::").next().unwrap_or(entry).to_owned())
        .collect()
}

/// A command's permission, as tauri-build names it.
pub fn allow(command: &str) -> String {
    format!("allow-{}", command.replace('_', "-"))
}

/// The main window's permission set: every registered command, since the main window is the app.
pub fn main_window_set(commands: &[String]) -> String {
    let permissions: String = commands.iter().map(|c| format!("  \"{}\",\n", allow(c))).collect();
    format!(
        "# Generated by build.rs from src/ipc.rs (D92). Do not edit.\n\n[[set]]\nidentifier = \"main-window\"\n\
         description = \"Every app command: the main window is the app.\"\npermissions = [\n{permissions}]\n"
    )
}
